#!/usr/bin/env python3
"""Headless stdio MCP smoke test for the repository-owned SonarQube launcher."""

from __future__ import annotations

import argparse
import json
import os
import queue
import re
import shutil
import signal
import subprocess
import sys
import threading
import time
import uuid
from pathlib import Path
from typing import Any


REQUIRED_TOOLS = {
    "search_sonar_issues_in_projects",
    "show_rule",
    "get_component_measures",
    "search_files_by_coverage",
    "get_project_quality_gate_status",
}
FORBIDDEN_TOOLS = {
    "change_sonar_issue_status",
    "change_security_hotspot_status",
    "toggle_automatic_analysis",
    "create_webhook",
    "delete_webhook",
}
RULE_KEY_FOR_SMOKE_TEST = "python:S117"


class ProbeError(RuntimeError):
    pass


def new_probe_container_name() -> str:
    return f"quality-mcp-probe-{uuid.uuid4().hex[:16]}"


def probe_container_cleanup_command(docker: str, name: str) -> list[str]:
    if not re.fullmatch(r"quality-mcp-probe-[0-9a-f]{16}", name):
        raise ProbeError("Refusing cleanup for a container name not generated by this probe.")
    return [docker, "container", "rm", "--force", name]


def terminate_process_tree(process: subprocess.Popen[str]) -> None:
    if process.poll() is not None:
        return
    if os.name == "nt":
        taskkill = shutil.which("taskkill") or "taskkill"
        try:
            subprocess.run(
                [taskkill, "/PID", str(process.pid), "/T", "/F"],
                check=False,
                capture_output=True,
                text=True,
                timeout=10,
            )
        except (OSError, subprocess.TimeoutExpired):
            process.kill()
    else:
        try:
            os.killpg(process.pid, signal.SIGTERM)
            process.wait(timeout=2)
        except (ProcessLookupError, subprocess.TimeoutExpired):
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        except OSError:
            process.kill()
    try:
        process.wait(timeout=3)
    except subprocess.TimeoutExpired:
        process.kill()
        process.wait(timeout=3)


def build_tool_arguments(name: str, schema: dict[str, Any], project_key: str) -> dict[str, Any]:
    """Build minimal read-only arguments from the advertised tool schema."""
    properties = schema.get("properties", {})
    candidates: dict[str, Any] = {
        "projectKey": project_key,
        "projectKeys": [project_key],
        "metricKeys": ["ncloc", "coverage"],
        "pageIndex": 1,
        "pageSize": 1,
        "key": RULE_KEY_FOR_SMOKE_TEST,
    }
    if name == "search_sonar_issues_in_projects":
        candidates.update({"projectKeys": [project_key], "pageIndex": 1, "pageSize": 1})
    elif name == "get_component_measures":
        candidates.update({"projectKey": project_key, "metricKeys": ["ncloc", "coverage"]})
    elif name == "search_files_by_coverage":
        candidates.update({"projectKey": project_key, "pageIndex": 1, "pageSize": 1})
    elif name == "get_project_quality_gate_status":
        candidates.update({"projectKey": project_key})
    elif name == "show_rule":
        candidates.update({"key": RULE_KEY_FOR_SMOKE_TEST})
    else:
        raise ProbeError(f"No read-only probe arguments are defined for {name!r}.")

    arguments = {key: value for key, value in candidates.items() if key in properties}
    required = schema.get("required", [])
    missing = [key for key in required if key not in arguments]
    if missing:
        raise ProbeError(f"Cannot safely call {name!r}; required fields lack probe values: {', '.join(missing)}")
    return arguments


class StdioMcpClient:
    def __init__(self, process: subprocess.Popen[str], deadline: float):
        self.process = process
        self.deadline = deadline
        self.lines: queue.Queue[str | None] = queue.Queue()
        self.next_id = 1
        self.reader = threading.Thread(target=self._read_stdout, daemon=True)
        self.reader.start()

    def _read_stdout(self) -> None:
        assert self.process.stdout is not None
        for line in self.process.stdout:
            self.lines.put(line)
        self.lines.put(None)

    def _remaining(self) -> float:
        remaining = self.deadline - time.monotonic()
        if remaining <= 0:
            raise ProbeError("MCP protocol probe exceeded its deadline.")
        return remaining

    def _read_message(self) -> dict[str, Any]:
        while True:
            try:
                line = self.lines.get(timeout=self._remaining())
            except queue.Empty as exc:
                raise ProbeError("MCP server did not answer before the deadline.") from exc
            if line is None:
                raise ProbeError(f"MCP server closed stdout (exit code {self.process.poll()}).")
            try:
                message = json.loads(line)
            except json.JSONDecodeError as exc:
                snippet = line.strip().replace("\r", " ")[:240]
                raise ProbeError(f"Non-JSON output polluted MCP stdout: {snippet!r}") from exc
            if not isinstance(message, dict):
                raise ProbeError("MCP stdout contained a non-object JSON message.")
            if "id" not in message:
                continue
            return message

    def request(self, method: str, params: dict[str, Any]) -> dict[str, Any]:
        assert self.process.stdin is not None
        request_id = self.next_id
        self.next_id += 1
        request = {"jsonrpc": "2.0", "id": request_id, "method": method, "params": params}
        self.process.stdin.write(json.dumps(request, separators=(",", ":")) + "\n")
        self.process.stdin.flush()
        while True:
            response = self._read_message()
            if response.get("id") != request_id:
                continue
            if "error" in response:
                raise ProbeError(f"MCP {method} failed: {response['error']}")
            result = response.get("result")
            if not isinstance(result, dict):
                raise ProbeError(f"MCP {method} returned no result object.")
            return result

    def notify(self, method: str) -> None:
        assert self.process.stdin is not None
        notification = {"jsonrpc": "2.0", "method": method}
        self.process.stdin.write(json.dumps(notification, separators=(",", ":")) + "\n")
        self.process.stdin.flush()

    def tools(self) -> list[dict[str, Any]]:
        tools: list[dict[str, Any]] = []
        cursor: str | None = None
        while True:
            params = {"cursor": cursor} if cursor else {}
            result = self.request("tools/list", params)
            page = result.get("tools")
            if not isinstance(page, list):
                raise ProbeError("MCP tools/list did not return a tools array.")
            tools.extend(tool for tool in page if isinstance(tool, dict))
            cursor = result.get("nextCursor")
            if not cursor:
                return tools

    def call_tool(self, name: str, arguments: dict[str, Any]) -> None:
        result = self.request("tools/call", {"name": name, "arguments": arguments})
        if result.get("isError") is True:
            details = result.get("content", [])
            raise ProbeError(f"Read-only MCP tool {name!r} returned an error: {details}")


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--launcher", required=True, type=Path, help="Start-SonarQubeMcp.ps1")
    parser.add_argument("--profile", required=True, choices=("BlazorAuto", "React"))
    parser.add_argument("--project-key", required=True, help="Derived main or SHA-specific candidate project key")
    parser.add_argument("--settings-path", type=Path, help="Optional ignored local settings file")
    parser.add_argument("--timeout-seconds", type=int, default=60)
    return parser.parse_args(argv)


def _probe_command(args: argparse.Namespace) -> list[str]:
    if not 1 <= args.timeout_seconds <= 300:
        raise ProbeError("Timeout must be between 1 and 300 seconds.")
    launcher = args.launcher.resolve(strict=True)
    if not launcher.is_file() or launcher.name.lower() != "start-sonarqubemcp.ps1":
        raise ProbeError("Launcher must be the repository's Start-SonarQubeMcp.ps1 file.")
    powershell = shutil.which("pwsh")
    if not powershell:
        raise ProbeError("PowerShell 7 (pwsh) was not found.")
    command = [
        powershell,
        "-NoProfile",
        "-File",
        str(launcher),
        "-FrontendProfile",
        args.profile,
        "-ProjectKey",
        args.project_key,
    ]
    if args.settings_path:
        command.extend(["-SettingsPath", str(args.settings_path.resolve())])
    return command


def _start_probe_process(command: list[str], probe_container: str) -> subprocess.Popen:
    process_env = os.environ.copy()
    process_env["SONAR_QUALITY_MCP_PROBE_CONTAINER"] = probe_container
    creation_flags = subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0
    return subprocess.Popen(
        command,
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace",
        bufsize=1,
        env=process_env,
        creationflags=creation_flags,
        start_new_session=os.name != "nt",
    )


def _drain_stderr(process: subprocess.Popen, lines: list[str]) -> None:
    assert process.stderr is not None
    for line in process.stderr:
        if len(lines) < 200:
            lines.append(line.rstrip())


def _call_read_only_tools(client: StdioMcpClient, project_key: str) -> tuple[str, set[str], list[str]]:
    initialized = client.request(
        "initialize",
        {
            "protocolVersion": "2025-06-18",
            "capabilities": {},
            "clientInfo": {"name": "blazorautoapp-sonar-probe", "version": "1.0"},
        },
    )
    protocol_version = initialized.get("protocolVersion")
    if not isinstance(protocol_version, str) or not protocol_version:
        raise ProbeError("MCP initialize did not negotiate a protocol version.")
    client.notify("notifications/initialized")

    tools = client.tools()
    names = {tool.get("name") for tool in tools if isinstance(tool.get("name"), str)}
    missing = sorted(REQUIRED_TOOLS - names)
    forbidden = sorted(FORBIDDEN_TOOLS & names)
    if missing:
        raise ProbeError(f"MCP server omitted required read tools: {', '.join(missing)}")
    if forbidden:
        raise ProbeError(f"Read-only MCP server exposed mutation tools: {', '.join(forbidden)}")

    by_name = {tool["name"]: tool for tool in tools if isinstance(tool.get("name"), str)}
    completed_calls: list[str] = []
    for name in sorted(REQUIRED_TOOLS):
        schema = by_name[name].get("inputSchema", {})
        client.call_tool(name, build_tool_arguments(name, schema, project_key))
        completed_calls.append(name)
    return protocol_version, names, completed_calls


def _cleanup_probe_process(
    process: subprocess.Popen,
    client: StdioMcpClient,
    stderr_reader: threading.Thread,
    docker: str,
    probe_container: str,
    succeeded: bool,
) -> None:
    if process.poll() is None:
        if process.stdin and not process.stdin.closed:
            process.stdin.close()
        try:
            process.wait(timeout=3)
        except subprocess.TimeoutExpired:
            terminate_process_tree(process)
    stderr_reader.join(timeout=3)
    client.reader.join(timeout=3)
    if process.stdout:
        process.stdout.close()
    if process.stderr:
        process.stderr.close()
    if succeeded:
        return
    try:
        cleanup = subprocess.run(
            probe_container_cleanup_command(docker, probe_container),
            check=False,
            capture_output=True,
            text=True,
            timeout=15,
        )
        if cleanup.returncode == 0 or re.search(r"No such (object|container)", cleanup.stderr, flags=re.IGNORECASE):
            return
        details = cleanup.stderr.strip().replace("\r", " ")[:500]
        print(f"MCP probe container cleanup failed: {details}", file=sys.stderr)
    except (OSError, subprocess.TimeoutExpired) as exc:
        print(f"MCP probe container cleanup failed: {exc}", file=sys.stderr)


def run_probe(args: argparse.Namespace) -> dict[str, Any]:
    command = _probe_command(args)
    docker = shutil.which("docker")
    if not docker:
        raise ProbeError("Docker CLI was not found for private probe cleanup.")
    probe_container = new_probe_container_name()
    started = time.monotonic()
    deadline = started + args.timeout_seconds
    process = _start_probe_process(command, probe_container)
    stderr_lines: list[str] = []
    stderr_reader = threading.Thread(target=_drain_stderr, args=(process, stderr_lines), daemon=True)
    stderr_reader.start()
    client = StdioMcpClient(process, deadline)
    succeeded = False
    try:
        protocol_version, names, completed_calls = _call_read_only_tools(client, args.project_key)
        if process.stdin:
            process.stdin.close()
        remaining = max(0.0, deadline - time.monotonic())
        process.wait(timeout=remaining)
        stderr_reader.join(timeout=3)
        if process.returncode != 0:
            diagnostics = " ".join(stderr_lines)[-1200:]
            raise ProbeError(f"MCP launcher exited {process.returncode}: {diagnostics}")
        succeeded = True
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise ProbeError(f"MCP process failed: {exc}") from exc
    finally:
        _cleanup_probe_process(process, client, stderr_reader, docker, probe_container, succeeded)

    return {
        "profile": args.profile,
        "projectKey": args.project_key,
        "protocolVersion": protocol_version,
        "toolCount": len(names),
        "readOnly": True,
        "calls": completed_calls,
        "elapsedSeconds": round(time.monotonic() - started, 2),
    }


def main(argv: list[str] | None = None) -> int:
    try:
        result = run_probe(parse_args(argv if argv is not None else sys.argv[1:]))
    except (ProbeError, OSError, ValueError) as exc:
        print(f"MCP probe failed: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
